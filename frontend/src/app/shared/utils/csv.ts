/** Builds a CSV string (RFC 4180 quoting) and triggers a browser download. */
export function downloadCsv(filename: string, headers: string[], rows: (string | number | boolean | null)[][]): void {
  const esc = (v: string | number | boolean | null): string => {
    const s = v === null ? '' : String(v);
    return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const csv = [headers, ...rows].map((r) => r.map(esc).join(',')).join('\r\n');
  const url = URL.createObjectURL(new Blob([csv], { type: 'text/csv;charset=utf-8;' }));
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
